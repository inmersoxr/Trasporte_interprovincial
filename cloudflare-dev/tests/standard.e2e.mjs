 const results=await Promise.all(bodies.map((body,i)=>owner.request.post(base+'/standard-api/api/bookings',{headers:{Authorization:'Bearer '+keys[i]},data:body})));
 assert.deepEqual(results.map(r=>r.status()).sort(),[200,409]);
 const won=results[0].status()===200?0:1,booking=(await results[won].json()).booking;
 const retry=await owner.request.post(base+'/standard-api/api/bookings',{headers:{Authorization:'Bearer '+keys[won]},data:bodies[won]});
 assert.equal((await retry.json()).booking.id,booking.id);
 const refund=await owner.request.post(base+'/standard-api/api/bookings/'+booking.id,{headers:{Authorization:'Bearer '+ownerKey},data:{action:'cancel'}});
